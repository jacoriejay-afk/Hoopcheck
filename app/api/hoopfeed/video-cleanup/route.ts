import { NextResponse } from "next/server";
import { createClient } from "@supabase/supabase-js";

export const runtime = "nodejs";

/** Remove a failed private video upload without exposing Storage DELETE to clients. */
export async function DELETE(request: Request) {
  const token = request.headers.get("authorization")?.match(/^Bearer\s+(\S+)$/i)?.[1];
  if (!token) return NextResponse.json({ error: "Sign in required" }, { status: 401 });
  const url = process.env.NEXT_PUBLIC_SUPABASE_URL;
  const key = process.env.SUPABASE_SERVICE_ROLE_KEY;
  if (!url || !key) return NextResponse.json({ error: "Unavailable" }, { status: 503 });
  const admin = createClient(url, key, { auth: { autoRefreshToken: false, persistSession: false } });
  const { data: { user }, error: authError } = await admin.auth.getUser(token);
  if (authError || !user) return NextResponse.json({ error: "Invalid session" }, { status: 401 });
  let payload: { path?: unknown };
  try { payload = await request.json(); } catch { return NextResponse.json({ error: "Invalid request" }, { status: 400 }); }
  const path = typeof payload.path === "string" ? payload.path : "";
  // Upload paths are generated by our signed-upload endpoint, not arbitrary user paths.
  const pattern = new RegExp("^" + user.id.replace(/[.*+?^${}()|[\]\\]/g, "\\$&") + "/[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\\.(mp4|webm|mov)$", "i");
  if (!pattern.test(path)) return NextResponse.json({ error: "Invalid video path" }, { status: 400 });
  const reference = "hoopfeed-private-videos/" + path;
  const { data: existing, error: lookupError } = await admin.from("feed_posts")
    .select("id").eq("video_url", reference).limit(1);
  if (lookupError) return NextResponse.json({ error: "Cleanup unavailable" }, { status: 503 });
  if (existing?.length) return NextResponse.json({ error: "Published videos cannot be removed here" }, { status: 409 });
  const { error } = await admin.storage.from("hoopfeed-private-videos").remove([path]);
  if (error) return NextResponse.json({ error: "Cleanup failed" }, { status: 503 });
  return NextResponse.json({ removed: true }, { headers: { "Cache-Control": "no-store" } });
}
