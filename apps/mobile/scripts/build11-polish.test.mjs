import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { test } from "node:test";
const read = path => readFileSync(new URL(path, import.meta.url), "utf8");
test("native navigation uses untinted clear glass while honoring accessibility and theme", () => {
  const surface = read("../components/GlassSurface.tsx");
  const tab = read("../components/TabBar.tsx");
  const theme = read("../src/theme.ts");
  assert.match(surface, /navigation && nativeGlass \? "transparent"/);
  assert.match(surface, /glassEffectStyle=\{navigation \? "clear" : "regular"\}/);
  assert.match(surface, /navigation \? undefined/);
  assert.match(surface, /colorScheme=\{theme.dark \? "dark" : "light"\}/);
  assert.match(tab, /backgroundColor: nativeGlass \? "transparent"/);
  assert.match(tab, /glassEffectStyle="clear"/);
  assert.match(tab, /PanResponder\.create/);
  assert.match(tab, /width: 24, height: 3/);
  assert.match(theme, /glassScope && dark/);
});
test("branded Feed, Explore, Alerts and Account preserve usable destinations", () => {
  const head = read("../components/glass/GlassHeader.tsx");
  const feed = read("../app/feed.tsx");
  const search = read("../app/search.tsx");
  const account = read("../app/account.tsx");
  const alerts = read("../app/notifications.tsx");
  assert.match(head, /"HOOPREELS" : "HOOPFEED"/);
  assert.doesNotMatch(head, /HoopBot/);
  assert.match(feed, /!reels \|\| posts.length === 0/);
  assert.match(read("../app/feed-welcome.tsx"), /<Redirect href="\/feed"/);
  assert.match(search, /<ExploreLinks compact/);
  assert.match(search, /fontFamily: "HoopCheckDisplay"/);
  assert.match(alerts, /HoopChat · messages and requests/);
  assert.match(alerts, /router.push\("\/messages"\)/);
  assert.doesNotMatch(account, /router.push\("\/messages"\)/);
  assert.match(account, /account.user.accountType==="player"\?<Pressable/);
  assert.match(account, /\/account\/edit/);
  assert.match(account, /\/membership/);
  assert.match(account, /\/account\/security/);
});
test("provider sync and prediction queries avoid stale oldest-500 truncation", () => {
  const sync = read("../../../app/api/cron/live-basketball/route.ts");
  const api = read("../../../app/api/game-predictions/route.ts");
  const board = read("../components/Scoreboard.tsx");
  assert.match(sync, /score_updated_at: receivedAt/);
  assert.match(sync, /date_offset/);
  assert.match(sync, /Object.keys\(payload.errors\).length > 0/);
  assert.match(sync, /range\(offset, offset \+ 499\)/);
  assert.match(api, /gte\("scheduled_at"/);
  assert.match(api, /lte\("scheduled_at", latest\)/);
  assert.match(api, /limit\(350\)/);
  assert.match(api, /limit\(150\)/);
  assert.match(board, /"RESULT PENDING"/);
  assert.match(board, /"UPDATE DELAYED"/);
  assert.match(board, /"Score refresh not verified"/);
});
