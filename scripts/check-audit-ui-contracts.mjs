// Static regression contracts for the November audit fixes.
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const read = path => readFileSync(new URL('../' + path, import.meta.url), 'utf8');
const review = read('app/teams/[id]/review/page.tsx');
const formStart = review.indexOf('<form');
const checkbox = review.indexOf('name="reviewRulesAccepted"');
const formEnd = review.indexOf('</form>', formStart);
assert.ok(formStart >= 0 && checkbox > formStart && checkbox < formEnd, 'Required review agreement stays inside the review form');
assert.match(review.slice(Math.max(formStart, checkbox - 90), checkbox + 90), /required/, 'Review agreement remains required');
const women = read('app/womens/[id]/page.tsx');
assert.ok(women.includes('country={team.country || t("international")}'), 'Women profile passes raw country to shared hero');
assert.ok(!women.includes('country={\x60\x24{countryFlag'), 'Women profile does not prefix a flag twice');
const account = read('app/account/page.tsx');
assert.ok(account.includes('profile.account_type === "player" && <SettingsRow') && account.includes('label="Career Passport"') && account.includes('href="/profile#career-passport"'), 'Career Passport shortcut is player-only');
const ownProfile = read('app/profile/page.tsx');
const journey = read('components/PlayerJourney.tsx');
const anchoredJourney = ownProfile.includes('<PlayerJourney') && journey.includes('<section id="career-passport"');
assert.ok(ownProfile.includes('id="career-passport"') || anchoredJourney, 'Career Passport deep link target exists');
assert.ok(!(ownProfile.includes('<div id="career-passport"') && journey.includes('<section id="career-passport"')),
  'Career Passport hash target must have one owner, not duplicate IDs');
const css = read('app/hoopcheck-directory-profile.css');
assert.ok(css.includes('hc-team-logo__crest path { fill: none !important;'), 'Fallback crest outline remains hollow');
const header = read('components/SiteHeader.tsx');
assert.match(header, /if\(!userId\)\{setAccountType\(""\);setIsAdmin\(false\);return;\}/, 'Logout clears both account role and admin navigation');
assert.match(header, /setAccountType\(""\);setIsAdmin\(false\);void Promise\.all/, 'Account switching clears stale role and admin navigation before loading new role');
console.log('PASS: review agreement, shared country flag, Career Passport navigation, crest outline, and auth navigation reset');

const contractPage=read('app/pre-sign/page.tsx');
const contractCheck=read('components/ContractRedFlagCheck.tsx');
assert.match(contractPage, /<ContractRedFlagCheck\/>/);
assert.match(contractCheck, /not contract analysis, verification or legal advice/);
assert.match(contractCheck, /does not establish that the contract is safe/);
assert.match(contractCheck, /onClick=\{\(\)=>setAnswers\(\{\}\)\}/);
assert.doesNotMatch(contractCheck, /localStorage|sessionStorage|fetch\(|supabase|<textarea|type="file"/);
const ts = (await import('typescript')).default;
const contractCode=ts.transpileModule(read('lib/contract-review-prompts.ts'),{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
const {CONTRACT_REVIEW_PROMPTS,summarizeContractReview}=await import('data:text/javascript;base64,'+Buffer.from(contractCode).toString('base64'));
const total=CONTRACT_REVIEW_PROMPTS.length;
assert.equal(new Set(CONTRACT_REVIEW_PROMPTS.map(item=>item.id)).size,total);
assert.equal(summarizeContractReview({}).unresolved.length,total);
const partial=summarizeContractReview({identity:'clear',pay:'concern',term:'unsure',unknown:'clear'});
assert.equal(partial.reviewed,3);
assert.equal(partial.concerns.length,1);
assert.equal(partial.unresolved.length,total-2);
assert.equal(summarizeContractReview({identity:'invalid'}).reviewed,0);
const clear=summarizeContractReview(Object.fromEntries(CONTRACT_REVIEW_PROMPTS.map(item=>[item.id,'clear'])));
assert.equal(clear.reviewed,total);
assert.equal(clear.concerns.length,0);
assert.equal(clear.unresolved.length,0);
console.log('PASS: temporary private contract self-assessment, explicit uncertainty, no safety certification');
